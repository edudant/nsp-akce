// Synthetic fixtures only; intentionally refuses every non-local Supabase URL.
import assert from 'node:assert/strict';
import { createHmac, randomUUID } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
const port = Number(process.env.NSP_TEST_PORT_BASE || 54321);
assert.ok(Number.isInteger(port) && port >= 1024 && port <= 65000);
const url = `http://127.0.0.1:${port}`;
const jwt = role => {
 const part = value => Buffer.from(JSON.stringify(value)).toString('base64url');
 const body = `${part({ alg: 'HS256', typ: 'JWT' })}.${part({ iss: 'supabase-demo', role, exp: Math.floor(Date.now() / 1000) + 3600 })}`;
 return `${body}.${createHmac('sha256', 'super-secret-jwt-token-with-at-least-32-characters-long').update(body).digest('base64url')}`;
};
const client = key => createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
const root = client(jwt('service_role'));
const ok = result => { if (result.error) throw new Error(result.error.message); return result.data; };
const ids = { user: randomUUID(), member: randomUUID(), season: randomUUID(), event: randomUUID() };
const email = `calendar-${ids.user}@example.invalid`, password = 'Local-calendar-test-27!';
let checks = 0;
const pass = name => { checks++; console.log(`OK ${name}`); };
const feed = (token, method = 'GET') => fetch(`${url}/functions/v1/calendar-feed?token=${token}`, { method });
try {
 ok(await root.from('members').insert({ id: ids.member, display_name: 'Calendar integration', short_name: 'CI', pairing_role: 'lead', experience_level: 'advanced', is_active: true }));
 ok(await root.from('member_accounts').insert({ member_id: ids.member, email, desired_role: 'member' }));
 const createdUser = ok(await root.auth.admin.createUser({ email, password, email_confirm: true }));
 ids.user = createdUser.user.id;
 const member = client(jwt('anon'));
 ok(await member.auth.signInWithPassword({ email, password }));
 const user = ok(await member.auth.getUser()).user;
 ids.user = user.id;
 ok(await root.from('seasons').insert({ id: ids.season, name: 'Calendar integration', kind: 'dance', date_from: '2025-01-01', date_to: '2030-12-31' }));
 ok(await root.from('events').insert({ id: ids.event, season_id: ids.season, type: 'rehearsal', title: 'Páteční zkouška', starts_at: '2028-03-26T01:30:00Z', ends_at: '2028-03-26T02:30:00Z', visibility: 'members', status: 'open', note: 'Veřejná poznámka; diakritika' }));
 const created = ok(await member.rpc('create_calendar_subscription', { subscription_kind: 'all' }));
 assert.ok(/^[0-9a-f]{64}$/.test(created.token));
 assert.ok((await member.from('calendar_subscriptions').select('*')).error);
 assert.ok((await member.rpc('get_calendar_feed', { token_digest: 'bad' })).error);
 assert.ok((await client(jwt('anon')).rpc('get_calendar_subscriptions')).error);
 pass('Authenticated RPC and table/projection isolation');
 let response = await feed(created.token);
 assert.equal(response.status, 200); assert.equal(response.headers.get('content-type'), 'text/calendar; charset=utf-8');
 assert.ok(response.headers.get('cache-control').includes('no-store'));
 let text = (await response.text()).replace(/\r\n /g, '');
 assert.ok(text.includes(`[Bez odpovědi] Páteční zkouška`));
 assert.ok(text.includes(`UID:${ids.event}@nsp-akce`));
 assert.ok(text.includes('DTSTART:20280326T013000Z')); assert.ok(!text.includes('VALARM'));
 response = await feed(created.token, 'HEAD'); assert.equal(response.status, 200); assert.equal(await response.text(), '');
 pass('Public GET/HEAD and Deno ICS response');
 ok(await member.rpc('mutate_app_v3', { action: 'response', payload: { id: ids.event, interest: 'maybe', note: 'SECRET personal note' } }));
 text = (await (await feed(created.token)).text()).replace(/\r\n /g, '');
 assert.ok(text.includes('[Zatím nevím] Páteční zkouška')); assert.ok(!text.includes('SECRET'));
 pass('Live member response update without personal note');
 ok(await root.from('events').update({ status: 'cancelled' }).eq('id', ids.event));
 text = (await (await feed(created.token)).text()).replace(/\r\n /g, '');
 assert.ok(text.includes('STATUS:CANCELLED')); assert.ok(text.includes(`UID:${ids.event}@nsp-akce`));
 pass('Cancellation preserves UID');
 const replacement = ok(await member.rpc('create_calendar_subscription', { subscription_kind: 'all' }));
 assert.equal((await feed(created.token)).status, 404); assert.equal((await feed(replacement.token)).status, 200);
 assert.ok(!JSON.stringify(ok(await member.rpc('get_calendar_subscriptions'))).includes(replacement.token));
 pass('Replacement invalidates previous token; metadata stays secret-free');
 ok(await root.from('members').update({ is_active: false }).eq('id', ids.member));
 assert.equal((await feed(replacement.token)).status, 404);
 ok(await root.from('members').update({ is_active: true }).eq('id', ids.member));
 ok(await root.from('profiles').update({ member_id: null }).eq('user_id', ids.user));
 assert.equal((await feed(replacement.token)).status, 404);
 ok(await root.from('profiles').update({ member_id: ids.member }).eq('user_id', ids.user));
 ok(await member.rpc('revoke_calendar_subscription', { subscription_kind: 'all' }));
 assert.equal((await feed(replacement.token)).status, 404);
 pass('Active member, account link and revocation checked on each download');
 assert.equal((await feed('invalid')).status, 404); assert.equal((await feed('invalid', 'POST')).status, 405);
 console.log(`Calendar integration checks passed: ${checks}`);
} finally {
 await root.from('events').delete().eq('id', ids.event);
 await root.auth.admin.deleteUser(ids.user);
 await root.from('members').delete().eq('id', ids.member);
 await root.from('seasons').delete().eq('id', ids.season);
}
